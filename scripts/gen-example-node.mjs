#!/usr/bin/env node
/**
 * Generate `docs/example-node.md` from the canonical skeleton.
 *
 * The example used to be hand-maintained, so it drifted: it advertised
 * `## Incoming relationships` as if the user wrote it (the plugin renders that
 * section dynamically), and it disagreed with the real skeleton on key order.
 * Now it is generated, and `--check` fails if the committed file is stale.
 *
 *   node scripts/gen-example-node.mjs          # write
 *   node scripts/gen-example-node.mjs --check  # fail on drift (for CI)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildHologramSkeleton } from '../src/skeleton.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'functional', 'example-node.md');

/**
 * The node the skeleton produces, with placeholder values standing in for a
 * user's. Kept here (not in src/) so the doc generator owns its own example.
 */
const EXAMPLE = {
	title: 'Node title',
	body: 'The seed. A sentence or two — it is fine to leave it half-written.',
	noteType: 'concept',
	created: '{{date}}',
	hologram: 'Parent Node',
};

/**
 * Frontmatter must be the very first bytes of the file, so the generated-file
 * marker cannot live above it without making this note uncopy-pasteable. It
 * goes in the body instead, where an HTML comment is inert markdown.
 */
const MARKER = `<!--
  GENERATED FILE — do not edit by hand.
  Regenerate: npm run gen:example
  Verify:     npm run check:example
  Source:     src/skeleton.ts

  A Semantic Node is two regions: the frontmatter above, and one body.
  The body is a single string; meaning is imposed on its slices by header
  delimiters and nothing else. Prose is never touched — it is simply whatever
  sits between the title and the first known header. Mark your own headings
  above the ## Relationships delimiter; a heading below it truncates the
  relation region.
-->
`;

/**
 * The three mirrors the plugin renders. Authored nowhere, rewritten on every
 * sync, listed here so a complete node is visible in one place.
 */
const GENERATED = `
<!-- ==== GENERATED BY THE PLUGIN — never author these ==== -->
<!--
  ## Incoming relationships
     Every relation pointing AT this note, with its strength. Read-only.

  ## Confidence
     local      — your felt confidence, from \`local-confidence:\`
     inherited  — summed from \`structural/subsumed-by\` children
     total      — local + inherited

  ## Gravitas
     Structural strength backed by evidence: each \`source\` note that
     \`lends-gravitas-to\` this one, scaled by its \`source-kind\`. An
     unprovenanced note shows 0%, which is honest rather than broken.
-->
`;

const content = buildHologramSkeleton(EXAMPLE).replace(/^# Node title$/m, `# Node title\n\n${MARKER}`).trimEnd() + '\n' + GENERATED;

const check = process.argv.includes('--check');
const current = await readFile(OUT, 'utf8').catch(() => null);

if (check) {
	if (current === null) {
		console.error(`drift: ${OUT} is missing. Run: npm run gen:example`);
		process.exit(1);
	}
	if (current !== content) {
		console.error(`drift: ${OUT} is stale. Run: npm run gen:example`);
		process.exit(1);
	}
	console.log('ok: docs/functional/example-node.md matches src/skeleton.ts');
} else {
	await writeFile(OUT, content, 'utf8');
	console.log(`wrote ${OUT}`);
}